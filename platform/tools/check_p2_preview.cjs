/* Offline browser regression. No network access or dependency downloads. */
const path=require('path'),fs=require('fs'),assert=require('assert');
const {chromium}=require(process.env.ENERGY_PLAYWRIGHT_MODULE||'/usr/lib/node_modules/@playwright/cli/node_modules/playwright');
const final=path.resolve(__dirname,'..');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.ENERGY_CHROME||'/usr/bin/google-chrome',args:['--no-sandbox','--disable-background-networking']});
 const page=await browser.newPage({viewport:{width:1280,height:900}}),errors=[];
 page.on('pageerror',err=>errors.push(String(err)));
 await page.route('**/*',route=>route.request().url().startsWith('file:')?route.continue():route.abort());
 await page.goto('file://'+path.join(final,'preview/index.html'));
 await page.waitForSelector('[data-role=detail] h2');
 assert((await page.locator('[data-role=detail]').innerText()).includes('新能源功率与负荷预测'));
 await page.locator('#ep-search').fill('构网');
 assert((await page.locator('[data-role=detail]').innerText()).includes('1,016'));
 assert((await page.locator('[data-role=detail]').innerText()).includes('份额持续上升'));
 await page.screenshot({path:path.join(final,'provenance/P2_PREVIEW_DESKTOP.png')});
 await page.locator('[data-mode=legacy]').click();
 await page.locator('#ep-search').fill('F0022');
 let text=await page.locator('[data-role=detail]').innerText();assert(text.includes('30,150')&&text.includes('1,493'));
 await page.locator('[data-topic=P01]').click();
 assert((await page.locator('[data-role=detail]').innerText()).includes('电力市场机制与交易'));
 await page.locator('[data-mode=cases]').click();
 assert((await page.locator('[data-role=detail]').innerText()).includes('未知'));
 await page.locator('#ep-search').fill('WindFloat');
 text=await page.locator('[data-role=detail]').innerText();assert(text.includes('TRL 9')&&text.includes('CRL 3'));
 await page.locator('[data-mode=topics]').click();
 await page.locator('#ep-search').fill('no-such-topic-for-browser-test');
 assert((await page.locator('[data-role=detail]').innerText()).includes('没有匹配结果'));
 await page.locator('#ep-search').fill('');
 await page.locator('#ep-category').selectOption('hydrogen');
 assert((await page.locator('[data-role=list]').innerText()).includes('电解水制氢'));
 await page.locator('#ep-category').selectOption('');
 await page.locator('#ep-search').fill('构网');
 await page.setViewportSize({width:390,height:844});
 await page.waitForTimeout(300);
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
 await page.screenshot({path:path.join(final,'provenance/P2_PREVIEW_MOBILE.png'),fullPage:true});
 assert.deepStrictEqual(errors,[]);
 const report={passed:true,checks:['initial_actual_data','topic_search','recomputed_growth','F0022_bridge','bridge_to_topic','unknown_axis','bounded_known_axes','empty_search','category_filter','mobile_no_horizontal_overflow','no_page_errors'],network_requests_allowed:false};
 fs.writeFileSync(path.join(final,'provenance/P2_BROWSER.json'),JSON.stringify(report,null,2)+'\n');
 console.log(report);
 await browser.close();
})().catch(err=>{console.error(err);process.exit(1)});
